typedef struct {
    int calls;
    int tiled_calls;
} tile_probe_ctx_t;

static int tile_probe_kernel(
    const tigris_plan_t *plan, const tigris_op_t *op, uint16_t op_index,
    tigris_mem_t *mem, void *user_ctx)
{
    (void)plan;
    (void)op;
    (void)op_index;
    tile_probe_ctx_t *ctx = (tile_probe_ctx_t *)user_ctx;
    ctx->calls++;
    if (mem->tile.active)
        ctx->tiled_calls++;
    return 0;
}

