/**
 * Copy a chain plan into a mutable buffer, force the head-stage line-buffered
 * flag on or off, run it through exec_chain_tiled with the float reference
 * kernels, and return a malloc'd copy of the model-output bytes (caller frees).
 * On return, *out_rows holds the total kernel output rows computed (0 unless
 * the row counter is compiled in). Returns NULL on failure.
 */
static uint8_t *run_chain_plan_with_flag(
    const uint8_t *plan_bytes, size_t plan_len, int flag_on,
    uint32_t *out_len, unsigned long *out_rows, tigris_kernel_fn kernel)
{
    *out_len = 0;
    *out_rows = 0;

    uint32_t buf_len = (uint32_t)plan_len;
    uint8_t *buf = (uint8_t *)malloc(plan_len);
    if (!buf) {
        tests_run++; tests_failed++;
        fprintf(stderr, "  FAIL: could not allocate plan copy\n");
        return NULL;
    }
    memcpy(buf, plan_bytes, plan_len);

    tigris_plan_t plan;
    tigris_error_t lerr = tigris_plan_load(buf, buf_len, &plan);
    TEST_ASSERT_EQ(lerr, TIGRIS_OK, "run_chain_plan: load plan");
    if (lerr != TIGRIS_OK) { free(buf); return NULL; }

    /* Loader is zero-copy: plan.stages aliases buf, so flip the flag byte in
     * place, then the loaded plan reflects it without reloading. */
    size_t reserved1_off =
        (size_t)((const uint8_t *)&plan.stages[0]._reserved1 - buf);
    if (reserved1_off + sizeof(uint16_t) > buf_len) {
        tests_run++; tests_failed++;
        fprintf(stderr, "  FAIL: reserved1 offset out of bounds\n");
        free(buf); return NULL;
    }
    if (flag_on)
        buf[reserved1_off] = (uint8_t)(buf[reserved1_off] |
            (uint8_t)(TIGRIS_STAGE_FLAG_LINE_BUFFERED & 0xFFu));
    else
        buf[reserved1_off] = (uint8_t)(buf[reserved1_off] &
            ~(uint8_t)(TIGRIS_STAGE_FLAG_LINE_BUFFERED & 0xFFu));

    int have_flag =
        (plan.stages[0]._reserved1 & TIGRIS_STAGE_FLAG_LINE_BUFFERED) != 0;
    TEST_ASSERT_EQ(have_flag, flag_on != 0, "run_chain_plan: flag state set");

#ifdef TIGRIS_COUNT_KERNEL_ROWS
    g_tigris_kernel_rows = 0;
#endif
    uint8_t *out = run_plan_capture_output(&plan, out_len, kernel);
#ifdef TIGRIS_COUNT_KERNEL_ROWS
    *out_rows = g_tigris_kernel_rows;
#endif

    free(buf);
    return out;
}

/**
 * The line-buffered roll must be BIT-EXACT with the recompute path and must
 * compute materially fewer kernel output rows. Runs a real 3-stage Conv chain
 * twice (flag set vs cleared), asserts byte-identical model output, and (when
 * the row counter is compiled in) asserts the line-buffered run computes fewer
 * rows, approaching the unique output-row count.
 *
 * linebuf_conv_chain: three padded 3x3-stride-1 Conv stages (composed halo 2
 * per stage), output H=64. Compiled at a 32K budget; the runtime re-derives a
 * small tile height against that budget (chain_tile_h=3 -> 22 tiles with a
 * partial last tile of 1 row), so a single run exercises tile 0, interior
 * tiles, and a partial last tile.
 */
static void test_exec_chain_tiled_line_buffered_rolls(void)
{
    printf("  test_exec_chain_tiled_line_buffered_rolls...\n");

    const uint8_t *plan_bytes = k_linebuf_conv_chain_plan;
    const size_t plan_len = sizeof(k_linebuf_conv_chain_plan);

    /* Model output height, for the recompute/roll row-count bounds. */
    uint8_t *pbuf = (uint8_t *)malloc(plan_len);
    memcpy(pbuf, plan_bytes, plan_len);
    tigris_plan_t p0;
    if (tigris_plan_load(pbuf, (uint32_t)plan_len, &p0) != TIGRIS_OK) {
        tests_run++; tests_failed++; free(pbuf); return;
    }
    uint16_t out_tidx = p0.model_outputs[0];
    int32_t out_h = tigris_tensor_shape(&p0, &p0.tensors[out_tidx])[1];
    (void)out_h;  /* only referenced by the row-count assertions below */
    free(pbuf);

    uint32_t len_on = 0, len_off = 0;
    unsigned long rows_on = 0, rows_off = 0;
    uint8_t *out_on = run_chain_plan_with_flag(
        plan_bytes, plan_len, 1, &len_on, &rows_on, tigris_dispatch_kernel);
#ifdef TIGRIS_COUNT_KERNEL_ROWS
    /* Effective tiling comes from the runtime's own budget-constrained tile
     * height, which is smaller than the compiler's stored value. */
    int32_t eff_tile_h = g_tigris_chain_tile_h;
    int32_t eff_tiles = g_tigris_chain_num_tiles;
    int32_t last_tile_h = out_h - (eff_tiles - 1) * eff_tile_h;
    printf("    tile_h=%d out_h=%d tiles=%d last_tile_h=%d interior_clamps=%d\n",
           eff_tile_h, out_h, eff_tiles, last_tile_h, g_tigris_interior_clamps);
    TEST_ASSERT(eff_tiles >= 3, "run has tile 0, interior tile(s), and a last tile");
    TEST_ASSERT(last_tile_h > 0 && last_tile_h < eff_tile_h,
                "the last tile is partial (exercises the partial-tile path)");
    /* This chain's composed halo makes the deepest stage bottom-clamp on
     * interior tiles (not just the last one), so some stages full-compute
     * while their chain siblings roll. The full-output byte-identity check
     * below validates that mixed fallback; assert it actually happened so a
     * future geometry change cannot silently drop the coverage. */
    TEST_ASSERT(g_tigris_interior_clamps >= 1,
                "an interior tile exercised the per-stage clamp fallback");
#endif
    uint8_t *out_off = run_chain_plan_with_flag(
        plan_bytes, plan_len, 0, &len_off, &rows_off, tigris_dispatch_kernel);

    TEST_ASSERT(out_on != NULL && out_off != NULL,
                "both flagged and cleared runs produced output");
    if (out_on && out_off) {
        TEST_ASSERT_EQ(len_on, len_off, "output length matches");
        TEST_ASSERT(len_on == len_off &&
                    memcmp(out_on, out_off, len_on) == 0,
                    "line-buffered output is byte-identical to recompute");
    }
#ifdef TIGRIS_COUNT_KERNEL_ROWS
    printf("    rows: line_buffered=%lu recompute=%lu (unique=%d)\n",
           rows_on, rows_off, 3 * out_h);
    TEST_ASSERT(rows_off > 0 && rows_on > 0, "row counter recorded work");
    TEST_ASSERT(rows_on < rows_off,
                "line-buffered computes materially fewer rows than recompute");
    /* Recompute must drop by a wide margin (interior tiles carry the halo). */
    TEST_ASSERT(rows_off - rows_on >= (unsigned long)(2 * out_h) / 3,
                "recompute reduction is material, not marginal");
    /* The three stages together emit 3*out_h unique output rows. The roll must
     * land near that (tile 0 and the last tile still re-establish boundary
     * halo), well below the recompute total. */
    unsigned long unique_rows = (unsigned long)(3 * out_h);
    TEST_ASSERT(rows_on < unique_rows + (unsigned long)unique_rows / 3,
                "line-buffered total approaches unique output rows (~1x)");
#endif
    free(out_on);
    free(out_off);
}

